-- Malha viária: paradas, rotas e itinerários

CREATE TABLE transport_stops (
    id CHAR(36) CHARACTER SET ascii COLLATE ascii_general_ci PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    description TEXT NULL,
    latitude DOUBLE NULL,
    longitude DOUBLE NULL,
    postal_code VARCHAR(9) NULL,
    street VARCHAR(255) NULL,
    number VARCHAR(30) NULL,
    complement VARCHAR(150) NULL,
    neighborhood VARCHAR(150) NULL,
    city VARCHAR(150) NULL,
    state_uf CHAR(2) NULL,
    landmark TEXT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    deleted_at DATETIME(6) NULL,
    KEY idx_stops_name (name),
    CONSTRAINT chk_stops_latitude CHECK (latitude IS NULL OR (latitude BETWEEN -90 AND 90)),
    CONSTRAINT chk_stops_longitude CHECK (longitude IS NULL OR (longitude BETWEEN -180 AND 180))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE transport_routes (
    id CHAR(36) CHARACTER SET ascii COLLATE ascii_general_ci PRIMARY KEY,
    school_id CHAR(36) CHARACTER SET ascii COLLATE ascii_general_ci NOT NULL,
    academic_year_id CHAR(36) CHARACTER SET ascii COLLATE ascii_general_ci NOT NULL,
    company_id CHAR(36) CHARACTER SET ascii COLLATE ascii_general_ci NULL,
    vehicle_id CHAR(36) CHARACTER SET ascii COLLATE ascii_general_ci NULL,
    driver_id CHAR(36) CHARACTER SET ascii COLLATE ascii_general_ci NULL,
    name VARCHAR(255) NOT NULL,
    shift VARCHAR(20) NOT NULL,
    route_type VARCHAR(20) NOT NULL DEFAULT 'rural',
    km_paved DOUBLE NOT NULL DEFAULT 0.00,
    km_unpaved DOUBLE NOT NULL DEFAULT 0.00,
    total_km DOUBLE GENERATED ALWAYS AS (km_paved + km_unpaved) STORED,
    departure_time TIME NULL,
    arrival_time TIME NULL,
    return_departure_time TIME NULL,
    is_outsourced BOOLEAN NOT NULL DEFAULT FALSE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    notes TEXT NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    deleted_at DATETIME(6) NULL,
    KEY idx_routes_school (school_id),
    KEY idx_routes_year (academic_year_id, is_active),
    KEY idx_routes_vehicle (vehicle_id),
    KEY idx_routes_driver (driver_id),
    CONSTRAINT fk_routes_school FOREIGN KEY (school_id) REFERENCES schools (id) ON DELETE RESTRICT,
    CONSTRAINT fk_routes_year FOREIGN KEY (academic_year_id) REFERENCES academic_years (id) ON DELETE RESTRICT,
    CONSTRAINT fk_routes_company FOREIGN KEY (company_id) REFERENCES transport_companies (id) ON DELETE SET NULL,
    CONSTRAINT fk_routes_vehicle FOREIGN KEY (vehicle_id) REFERENCES transport_vehicles (id) ON DELETE SET NULL,
    CONSTRAINT fk_routes_driver FOREIGN KEY (driver_id) REFERENCES transport_drivers (id) ON DELETE SET NULL,
    CONSTRAINT chk_routes_shift CHECK (shift IN ('morning', 'afternoon', 'night', 'full_day')),
    CONSTRAINT chk_routes_type CHECK (route_type IN ('rural', 'urban', 'mixed')),
    CONSTRAINT chk_routes_km CHECK (km_paved >= 0 AND km_unpaved >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE transport_route_stops (
    id CHAR(36) CHARACTER SET ascii COLLATE ascii_general_ci PRIMARY KEY,
    route_id CHAR(36) CHARACTER SET ascii COLLATE ascii_general_ci NOT NULL,
    stop_id CHAR(36) CHARACTER SET ascii COLLATE ascii_general_ci NOT NULL,
    sequence_order INT NOT NULL,
    estimated_pickup_time TIME NULL,
    estimated_dropoff_time TIME NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    UNIQUE KEY uq_route_stops_sequence (route_id, sequence_order),
    UNIQUE KEY uq_route_stops_stop (route_id, stop_id),
    CONSTRAINT fk_route_stops_route FOREIGN KEY (route_id) REFERENCES transport_routes (id) ON DELETE CASCADE,
    CONSTRAINT fk_route_stops_stop FOREIGN KEY (stop_id) REFERENCES transport_stops (id) ON DELETE CASCADE,
    CONSTRAINT chk_route_stops_sequence CHECK (sequence_order > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
