-- Frota: empresas, motoristas, veículos e vistorias

CREATE TABLE transport_companies (
    id CHAR(36) CHARACTER SET ascii COLLATE ascii_general_ci PRIMARY KEY,
    legal_name VARCHAR(255) NOT NULL,
    cnpj VARCHAR(18) NOT NULL,
    contract_number VARCHAR(100) NULL,
    contract_start_date DATE NULL,
    contract_end_date DATE NULL,
    responsible_name VARCHAR(255) NULL,
    phone VARCHAR(30) NULL,
    email VARCHAR(255) NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    notes TEXT NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    deleted_at DATETIME(6) NULL,
    UNIQUE KEY uq_companies_cnpj (cnpj),
    KEY idx_companies_name (legal_name),
    CONSTRAINT chk_companies_contract CHECK (contract_end_date IS NULL OR contract_start_date IS NULL OR contract_end_date >= contract_start_date)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE transport_drivers (
    id CHAR(36) CHARACTER SET ascii COLLATE ascii_general_ci PRIMARY KEY,
    company_id CHAR(36) CHARACTER SET ascii COLLATE ascii_general_ci NULL,
    full_name VARCHAR(255) NOT NULL,
    cpf VARCHAR(14) NOT NULL,
    birth_date DATE NOT NULL,
    cnh_number VARCHAR(30) NOT NULL,
    cnh_category CHAR(1) NOT NULL,
    cnh_expiration_date DATE NOT NULL,
    course_certificate VARCHAR(100) NULL,
    course_expiration_date DATE NULL,
    toxicological_exam_date DATE NULL,
    toxicological_expiration_date DATE NULL,
    phone VARCHAR(30) NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    notes TEXT NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    deleted_at DATETIME(6) NULL,
    UNIQUE KEY uq_drivers_cpf (cpf),
    UNIQUE KEY uq_drivers_cnh (cnh_number),
    KEY idx_drivers_company (company_id),
    KEY idx_drivers_name (full_name),
    CONSTRAINT fk_drivers_company FOREIGN KEY (company_id) REFERENCES transport_companies (id) ON DELETE SET NULL,
    CONSTRAINT chk_drivers_cnh_category CHECK (cnh_category IN ('D', 'E'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE transport_vehicles (
    id CHAR(36) CHARACTER SET ascii COLLATE ascii_general_ci PRIMARY KEY,
    company_id CHAR(36) CHARACTER SET ascii COLLATE ascii_general_ci NULL,
    description VARCHAR(255) NOT NULL,
    plate VARCHAR(10) NOT NULL,
    renavam VARCHAR(30) NULL,
    chassis VARCHAR(30) NULL,
    brand_model VARCHAR(150) NULL,
    manufacture_year INT NULL,
    model_year INT NULL,
    passenger_capacity INT NOT NULL,
    network_type VARCHAR(20) NOT NULL DEFAULT 'rural',
    vehicle_type_inep INT NOT NULL,
    is_exclusive_school_use BOOLEAN NOT NULL DEFAULT TRUE,
    is_accessible_disability BOOLEAN NOT NULL DEFAULT FALSE,
    last_inspection_date DATE NULL,
    inspection_certificate_number VARCHAR(100) NULL,
    inspection_valid_until DATE NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    deactivation_reason TEXT NULL,
    notes TEXT NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    deleted_at DATETIME(6) NULL,
    UNIQUE KEY uq_vehicles_plate (plate),
    KEY idx_vehicles_company (company_id),
    KEY idx_vehicles_capacity (passenger_capacity),
    CONSTRAINT fk_vehicles_company FOREIGN KEY (company_id) REFERENCES transport_companies (id) ON DELETE SET NULL,
    CONSTRAINT chk_vehicles_capacity CHECK (passenger_capacity > 0),
    CONSTRAINT chk_vehicles_network CHECK (network_type IN ('rural', 'urban', 'mixed')),
    CONSTRAINT chk_vehicles_inep CHECK (vehicle_type_inep BETWEEN 1 AND 11)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE vehicle_inspections (
    id CHAR(36) CHARACTER SET ascii COLLATE ascii_general_ci PRIMARY KEY,
    vehicle_id CHAR(36) CHARACTER SET ascii COLLATE ascii_general_ci NOT NULL,
    inspection_date DATE NOT NULL,
    certificate_number VARCHAR(100) NOT NULL,
    valid_until DATE NOT NULL,
    notes TEXT NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    KEY idx_inspections_vehicle (vehicle_id, valid_until),
    CONSTRAINT fk_inspections_vehicle FOREIGN KEY (vehicle_id) REFERENCES transport_vehicles (id) ON DELETE CASCADE,
    CONSTRAINT chk_inspections_validity CHECK (valid_until >= inspection_date)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
